"""Pick each sample's best setting (biggest saving vs AVIF at equal quality)
and copy the finished outputs into samples/<name>/:
  original.png, <name>.gsq, decoded.png, decoded_x4.png, avif_same_size.png,
  comparison.png  (+ samples/README.md with the numbers)
usage: python publish_samples.py   (after: bench.py ... --tag samples)
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent
OUT, SAM = ROOT / "out", ROOT / "samples"
RUST = ROOT / "gsq_rs" / "target" / "release" / "gsq_view.exe"
INFO = {
    "spheres": "Glossy spheres, ray-traced by `make_samples.py` (this repo)",
    "ribbons": "Abstract glossy colour ribbons, generated by `make_samples.py` (this repo)",
    "earthrise": "Apollo 8 *Earthrise*, NASA photo AS08-14-2383, 24 Dec 1968 (public domain)",
}

rows = []
for f in ("results_samples.json", "results_samples2.json"):
    if (OUT / f).exists():
        rows += json.load(open(OUT / f))
CODECS = ("jpeg", "webp", "avif")
lines = ["# Samples", "",
         "Each image is encoded at the setting with the biggest quality lead over the **best** of JPEG, "
         "WebP and AVIF at the same file size. JPEG and AVIF are tried with both 4:2:0 and 4:4:4 colour; "
         "WebP with sharp YUV.",
         "",
         "Every folder has:",
         "- `original.png`",
         "- the blob file `*.gsq`",
         "- `decoded.png`: the blob file opened again",
         "- `decoded_x4.png`: the same file drawn at 4× size",
         "- `avif_same_size.png`: AVIF given the same number of bytes",
         "- `comparison.png`",
         "",
         "| Sample | Source | Blobs | Blob file | Our quality | JPEG / WebP / AVIF at the same size | Result |",
         "|---|---|---|---|---|---|---|"]
for name in INFO:
    cand = [r for r in rows if r["image"] == name]

    def margin(r):  # our PSNR minus the best other codec at the same size
        return r["psnr_file"] - max(r[c] for c in CODECS if r[c] is not None)

    best = max(cand, key=margin)
    stem = f"{name}_{best['N']}_sq_{best['lam']}"
    d = SAM / name
    shutil.copy(OUT / f"{stem}.gsq", d / f"{name}.gsq")
    shutil.copy(OUT / f"{stem}_gs.png", d / "decoded.png")
    shutil.copy(OUT / f"{stem}_avif.png", d / "avif_same_size.png")
    subprocess.run([str(RUST), str(d / f"{name}.gsq"), str(d / "decoded_x4.png"), "--scale", "4"], check=True)
    subprocess.run([sys.executable, str(ROOT / "make_figure.py"), name, str(best["N"]), str(best["lam"])], check=True, cwd=ROOT)
    shutil.copy(OUT / f"figure_{name}.png", d / "comparison.png")
    m = margin(best)
    need = [best[f"{c}_bytes_same_psnr"] for c in CODECS if best[f"{c}_bytes_same_psnr"]]
    if m > 0:
        verdict = f"✅ **+{m:.2f} dB** over the best of them; " + (
            f"the best needs {min(need) / 1024:.1f} KB for our quality" if need
            else "none of them reaches our quality at any size")
    else:
        verdict = f"❌ {m:.2f} dB behind; the best needs only {min(need) / 1024:.1f} KB for our quality"
    others = " / ".join(f"{best[c]:.2f}" for c in CODECS)
    lines.append(f"| [{name}]({name}/) | {INFO[name]} | {best['kept']:,} | {best['bytes'] / 1024:.1f} KB "
                 f"(PNG {best['png_bytes'] / 1024:.0f} KB) | **{best['psnr_file']:.2f} dB** | {others} dB | {verdict} |")
    print(name, best["N"], best["lam"], best["bytes"], best["psnr_file"], "margin dB", round(m, 2))
lines += ["", "Open any `.gsq` yourself (no Python or GPU needed):", "```",
          "gsq_view.exe samples/spheres/spheres.gsq out.png --scale 4 --csv blobs.csv", "```"]
(SAM / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(SAM / "README.md")
